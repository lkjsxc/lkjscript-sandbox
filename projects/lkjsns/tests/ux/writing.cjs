const {resourceId,isResource,isEditor,chromium,base,fixture,output,path,assert,form,fields,click,goto,pass,session,submit,createPost,save}=require('./support.cjs');
(async()=>{
 const browser=await chromium.launch({headless:true});
 try {
  const context=await session(browser);const p=await context.newPage();p.setDefaultTimeout(20000);
  await goto(p,'/compose');
  assert.equal(await p.locator('[name=body]').evaluate(el=>el===document.activeElement),true);
  const textarea=await p.locator('[name=body]').evaluate(el=>({border:getComputedStyle(el).borderTopWidth,width:el.getBoundingClientRect().width}));
  assert(parseFloat(textarea.border)>=1);assert(textarea.width>300);
  assert.equal(await p.getByText('Your post',{exact:true}).count(),0);
  assert.equal(await p.getByText(/Members means everyone registered/).count(),0);
  const labels=await p.locator('.form-actions button').allTextContents();
  assert.deepEqual(labels,['Attach file','Post']);
  assert.equal(await p.locator('a[href="/drafts"]').count(),0);
  assert.equal(await p.locator('main').getByText(/Drafts are saved|Draft saved|Save draft|Save & preview/).count(),0);
  pass('Autofocused composer exposes only Attach file and Post, without draft controls or saving notices');
  const preference=p.waitForResponse(r=>r.url()===base+'/action'&&r.request().postData()?.includes('intent=audience'));
  await p.locator('select[name=audience]').selectOption('public');assert.equal((await preference).status(),204);
  await goto(p,'/');await goto(p,'/compose');assert.equal(await p.locator('[name=audience]').inputValue(),'public');
  const state=await context.storageState();const fresh=await browser.newContext({storageState:{cookies:state.cookies,origins:[]}});
  const independent=await fresh.newPage();await goto(independent,'/compose');assert.equal(await independent.locator('[name=audience]').inputValue(),'public');await fresh.close();
  pass('Unsaved audience selection persists in the server, not just local storage');
  await p.locator('[name=body]').fill('A small observation from the riverside.');
  await click(p,p.getByRole('button',{name:'Attach file',exact:true}));
  const draft=new URL(p.url()).searchParams.get('draft');assert(draft);
  assert.equal(new URL(p.url()).pathname,'/pick');
  await click(p,p.getByRole('link',{name:'Back to writing',exact:true}));
  assert.equal(await p.locator('[name=body]').inputValue(),'A small observation from the riverside.');
  assert.equal(await p.locator('[name=audience]').inputValue(),'public');
  assert.equal(await p.locator('.preview-card,.preview-summary').count(),0);
  assert.equal(await p.locator('main').getByText(/Draft saved|Drafts are saved|Your draft/).count(),0);
  pass('Attachment selection quietly retains text and audience without a save or preview step');
  await p.screenshot({path:path.join(output,'writing-desktop.png'),fullPage:true});
  assert.equal(await p.getByRole('link',{name:'Delete post',exact:true}).count(),1);
  await p.locator('[name=body]').fill('Unsubmitted text must survive Cancel.');
  await p.getByRole('link',{name:'Delete post',exact:true}).click();await p.getByRole('dialog').waitFor();assert(isEditor(p.url())||new URL(p.url()).pathname==='/compose');
  assert.equal(await p.locator('input[type=checkbox]').count(),0);
  await p.getByRole('dialog').getByRole('button',{name:'Cancel',exact:true}).click();assert(isEditor(p.url())||new URL(p.url()).pathname==='/compose');
  assert.equal(await p.locator('[name=body]').inputValue(),'Unsubmitted text must survive Cancel.');
  await p.locator('[name=body]').fill('A small observation from the riverside.');
  pass('Direct delete action opens a single native confirmation; Cancel preserves unsubmitted writing');
  const publicId=draft;
  await click(p,p.getByRole('button',{name:'Post',exact:true}));assert.equal(new URL(p.url()).pathname,'/');
  await goto(p,'/');const card=p.locator('article.note').filter({hasText:'A small observation from the riverside.'});
  await click(p,card.getByText('A small observation from the riverside.',{exact:true}));
  assert.equal(resourceId(p.url()),publicId);
  pass('Clicking a post body opens its permalink');
  const member=await session(browser,'member');const mp=await member.newPage();await goto(mp,'/note?id='+publicId);
  const attention=form(mp,'eyes');assert.equal(await attention.count(),1);
  assert((await attention.innerText()).includes('Attention'));
  await click(mp,attention.locator('button'));assert(isResource(mp.url()));
  assert.equal(await form(mp,'eyes').locator('button').getAttribute('aria-pressed'),'true');
  await goto(p,'/notifications');assert((await p.locator('body').innerText()).includes('attention'));
  assert((await p.locator('h1').getAttribute('class')).includes('sr-only'));
  pass('Attention action and notification wording');
  const membersId=await createPost(p,'Private constellation note for registered members.','members');
  const protectedDraft=await createPost(p,'Never-published private draft nebula.','members','draft');
  save('posts',{publicId,membersId,protectedDraft});
  // A stale edit must not replace the newest draft or discard the attempted input.
  await goto(p,'/compose?id='+protectedDraft);const stale=await fields(p,'note');
  const current=await submit(p,'note',{body:'Newest private draft nebula.',mode:'draft'});
  const response=await context.request.post(base+'/action',{form:{...stale,body:'Unsaved conflicting draft nebula.',mode:'draft'},headers:{Origin:base},maxRedirects:0});
  assert.equal(response.status(),409);assert((await response.text()).includes('Unsaved conflicting draft nebula.'));
  await goto(p,'/compose?id='+protectedDraft);assert.equal(await p.locator('[name=body]').inputValue(),'Newest private draft nebula.');
  pass('Optimistic conflict preserves attempted text without overwriting saved work');
  await p.setViewportSize({width:390,height:844});await p.screenshot({path:path.join(output,'compose-mobile.png'),fullPage:true});
 } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
