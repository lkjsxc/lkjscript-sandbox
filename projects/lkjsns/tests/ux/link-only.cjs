// Synthetic browser acceptance for capability-based post and file access.
'use strict';
const {chromium,base,output,path,assert,form,click,goto,pass,session}=require('./support.cjs');
(async()=>{
 const browser=await chromium.launch({headless:true});
 try{
  const owner=await session(browser),p=await owner.newPage();p.setDefaultTimeout(30000);
  await goto(p,'/');await click(p,p.locator('.sidebar a[href="/compose"]'));
  const id=await p.locator('input[name=id]').inputValue();
  await p.locator('textarea[name=body]').fill('Unlisted **telescope** with attached image');
  await p.locator('select[name=audience]').selectOption('link-only');
  await click(p,p.getByRole('button',{name:'Attach file',exact:true}));
  await click(p,p.getByRole('link',{name:/Upload/}).first());
  await p.locator('input[type=file]').setInputFiles(path.join(output,'media','landscape-1.png'));
  await click(p,p.getByRole('button',{name:'Upload',exact:true}));
  assert.equal(await p.locator('[name=audience]').inputValue(),'link-only');
  const attachment=await p.locator('.composer-attachments img').getAttribute('src');
  const mediaId=new URL(attachment,base).pathname.split('/')[1];
  await click(p,p.getByRole('button',{name:'Post',exact:true}));
  assert.equal(new URL(p.url()).pathname,'/');
  await goto(p,'/link-posts');
  const card=p.locator('article.note').filter({hasText:'Unlisted telescope with attached image'});
  assert.equal(await card.count(),1);
  const share=await card.getByRole('link',{name:'Share link'}).getAttribute('href');
  const sharedURL=new URL(share,base);assert.equal(sharedURL.pathname,'/'+id);assert.match(sharedURL.searchParams.get('share'),/^[a-f0-9]{64}$/);
  const guest=await browser.newContext();const anonymous=await guest.newPage();
  assert.equal((await guest.request.get(base+'/'+id)).status(),404);
  assert.equal((await guest.request.get(base+'/'+mediaId+'/raw?note='+id)).status(),404);
  const wrong=new URL(sharedURL);wrong.searchParams.set('share','f'.repeat(64));
  assert.equal((await guest.request.get(wrong.href)).status(),404);
  await goto(anonymous,sharedURL.pathname+sharedURL.search);
  assert((await anonymous.locator('main').innerText()).includes('Unlisted telescope'));
  assert.equal(await anonymous.locator('.note-detail .note-body strong').innerText(),'telescope');
  assert.equal(await anonymous.locator('meta[name=robots]').getAttribute('content'),'noindex, nofollow');
  assert.equal(await anonymous.locator('meta[name=referrer]').getAttribute('content'),'strict-origin');
  let externalReferrer='';
  await anonymous.route('https://referrer-check.invalid/**',async route=>{externalReferrer=route.request().headers().referer||'';await route.fulfill({status:200,headers:{'Access-Control-Allow-Origin':'*'},body:''});});
  await anonymous.evaluate(()=>{const link=document.createElement('a');link.id='referrer-check';link.href='https://referrer-check.invalid/probe';link.textContent='referrer check';document.body.append(link);});
  await click(anonymous,anonymous.locator('#referrer-check'));
  assert(!externalReferrer.includes(sharedURL.searchParams.get('share')));
  await goto(anonymous,sharedURL.pathname+sharedURL.search);
  const raw=await anonymous.locator('.note-detail .media-grid img').getAttribute('src');
  assert(new URL(raw,base).searchParams.has('share'));
  const bytes=await guest.request.get(base+raw,{headers:{Range:'bytes=0-7'}});assert.equal(bytes.status(),206);
  assert.equal((await bytes.body()).length,8);
  await goto(anonymous,'/');assert.equal(await anonymous.getByText('Unlisted telescope with attached image').count(),0);
  await goto(anonymous,'/search?q=telescope');assert.equal(await anonymous.getByText('Unlisted telescope with attached image').count(),0);
  await goto(anonymous,'/@testowner');assert.equal(await anonymous.getByText('Unlisted telescope with attached image').count(),0);
  pass('Link-only posts and referenced media require the full share capability and do not appear in discovery');

  const member=await session(browser,'member'),m=await member.newPage();
  await goto(m,sharedURL.pathname+sharedURL.search);
  await click(m,form(m,'bookmark').locator('button'));
  await goto(m,'/saved');
  const saved=m.locator('article.note').filter({hasText:'Unlisted telescope with attached image'});
  assert.equal(await saved.count(),1);
  const savedTarget=await saved.getAttribute('data-href');assert.equal(new URL(savedTarget,base).searchParams.get('share'),sharedURL.searchParams.get('share'));
  await goto(m,sharedURL.pathname+sharedURL.search);
  await click(m,m.locator('.note-detail').getByRole('link',{name:/^Reply/}));
  assert.equal(await m.locator('[name=audience]').inputValue(),'link-only');
  await m.locator('[name=body]').fill('A **reply** visible only inside the shared thread');
  await click(m,m.getByRole('button',{name:'Post',exact:true}));
  assert.equal(new URL(m.url()).pathname+new URL(m.url()).search,sharedURL.pathname+sharedURL.search);
  assert((await m.locator('main').innerText()).includes('A reply visible only inside the shared thread'));
  await goto(anonymous,sharedURL.pathname+sharedURL.search);
  assert((await anonymous.locator('main').innerText()).includes('A reply visible only inside the shared thread'));
  assert.equal(await anonymous.locator('.reply-list .note-body strong').innerText(),'reply');
  pass('Bookmarks and replies retain access only within the shared thread');
  await member.close();await guest.close();
 }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
