// Synthetic browser test of multi-chunk posts and their access controls.
const {chromium,base,assert,goto,pass,session,crypto}=require('./support.cjs');
const fs=require('fs'),path=require('path');
(async()=>{const browser=await chromium.launch({headless:true});try{
 const owner=await session(browser),p=await owner.newPage();p.setDefaultTimeout(120000);
 await goto(p,'/compose');const id=await p.locator('[name=id]').inputValue();
 const csrf=await p.locator('[name=csrf]').inputValue(),blob=crypto.randomBytes(32).toString('hex');
 const url=base+'/post-body/start?id='+blob,fields={post:id,version:'0',size:'70000'};
 let denied=await owner.request.post(url,{headers:{Origin:'https://example.invalid','X-CSRF-Token':csrf},form:fields});
 assert.equal(denied.status(),403);
 denied=await owner.request.post(url,{headers:{Origin:base,'X-CSRF-Token':'0'.repeat(64)},form:fields});
 assert.equal(denied.status(),403);
 const outsider=await browser.newContext();denied=await outsider.request.post(url,{headers:{Origin:base,'X-CSRF-Token':csrf},form:fields});
 assert.equal(denied.status(),403);await outsider.close();
 denied=await owner.request.post(url+'&id='+blob,{headers:{Origin:base,'X-CSRF-Token':csrf},form:fields});
 assert.equal(denied.status(),400);
 pass('Post body transfers enforce origin, session, CSRF, and strict query admission');
 const value='a'.repeat(4194303)+'🌱'+'Z'.repeat(120)+' THE_UNIQUE_TAIL';
 await p.locator('[name=body]').fill(value);await p.locator('[name=audience]').selectOption('public');
 await Promise.all([p.waitForURL(base+'/',{timeout:180000}),p.getByRole('button',{name:'Post',exact:true}).click()]);
 const guest=await browser.newContext(),g=await guest.newPage();
 const read=async part=>{const r=await g.request.get(base+'/post-body/raw?note='+id+'&part='+part+'&version=1');assert.equal(r.status(),200);return r.text();};
 const first=await read(0),second=await read(1);assert.equal(first+second,value);
 const crossing=await g.request.get(base+'/post-body/read?note='+id+'&version=1&fragment=1&offset=4194299');
 const next=await g.request.get(base+'/post-body/read?note='+id+'&version=1&fragment=1&offset=4194303&line=1');
 assert.equal(crossing.status(),200);assert.equal(next.status(),200);
 const nextText=await next.text();assert(nextText.includes('🌱') && nextText.includes('THE_UNIQUE_TAIL'));
 await goto(g,'/'+id);await g.locator('.note-detail').getByRole('link',{name:'Read full post'}).click();
 await g.waitForFunction(()=>document.querySelector('[data-post-complete]')?.textContent.includes('THE_UNIQUE_TAIL') &&
   document.querySelector('[data-post-status]')?.hidden,null,{timeout:180000});
 assert.equal(await g.locator('[data-post-complete]').textContent(),value);
 assert.equal(await g.locator('.post-body-page a[rel=next], .post-body-page a[rel=prev]').count(),0);
 assert.equal((await g.request.get(base+'/post-body/raw?note='+id+'&part=2&version=1')).status(),404);
 await goto(p,'/'+id+'/edit');await p.locator('[name=body]:not([disabled])').waitFor({timeout:180000});
 const oldBlob=await p.locator('.composer').getAttribute('data-body-blob');assert(/^[0-9a-f]{64}$/.test(oldBlob));
 assert.equal(await p.locator('[name=body]').inputValue(),value);
 await p.locator('[name=body]').fill('A small edited post.');
 await Promise.all([p.waitForURL(new RegExp('/'+id+'(?:\\?.*)?$'),{timeout:180000}),p.getByRole('button',{name:'Save changes'}).click()]);
 assert.equal((await g.request.get(base+'/post-body/raw?note='+id+'&part=0&version=2')).status(),404);
 const oldParts=path.join(process.env.LKJSNS_TEST_FIXTURE,'objects','lkjsns','post-parts',oldBlob);
 assert(fs.existsSync(path.join(oldParts,'0')) && fs.existsSync(path.join(oldParts,'1')));
 fs.writeFileSync(path.join(process.env.LKJSNS_TEST_FIXTURE,'postgc-test.json'),JSON.stringify({oldBlob,queued:Date.now()}));
 pass('Multi-chunk Unicode posts round-trip and editing replaces the previous body safely');
 await guest.close();

 await goto(p,'/compose');const privateId=await p.locator('[name=id]').inputValue(),privateBody='private body '.repeat(7000)+' private end';
 await p.locator('[name=body]').fill(privateBody);await p.locator('[name=audience]').selectOption('members');
 await Promise.all([p.waitForURL(base+'/',{timeout:180000}),p.getByRole('button',{name:'Post',exact:true}).click()]);
 const anonymous=await browser.newContext(),member=await session(browser,'member');
 assert.equal((await anonymous.request.get(base+'/post-body/raw?note='+privateId+'&part=0&version=1')).status(),404);
 const visible=await member.request.get(base+'/post-body/raw?note='+privateId+'&part=0&version=1');assert.equal(visible.status(),200);assert.equal(await visible.text(),privateBody);
 const fragment=base+'/post-body/read?note='+privateId+'&version=1&fragment=1';
 assert.equal((await anonymous.request.get(fragment)).status(),404);
 assert.equal((await member.request.get(fragment)).status(),200);
 assert.equal((await member.request.get(fragment+'&fragment=1')).status(),400);
 assert.equal((await member.request.get(fragment+'&line=2')).status(),400);
 pass('Chunked member-only post bodies and reading fragments require current post access');
 await anonymous.close();await member.close();

 await goto(p,'/compose');const entered='Network recovery '.repeat(5000)+' keep this ending';
 await p.locator('[name=body]').fill(entered);
 await p.route('**/post-body/part?**',route=>route.abort());
 await p.getByRole('button',{name:'Post',exact:true}).click();
 await p.waitForFunction(() => /interrupted|still here/i.test(document.querySelector('.post-transfer-status')?.textContent || ''), null, {timeout:120000});
 assert.equal(await p.locator('[name=body]').inputValue(),entered);
 await p.unroute('**/post-body/part?**');await p.getByRole('button',{name:'Discard unfinished upload'}).click();
 await p.waitForFunction(() => /discarded/i.test(document.querySelector('.post-transfer-status')?.textContent || ''), null, {timeout:30000});
 assert.equal(await p.locator('[name=body]').inputValue(),entered);
 pass('Interrupted chunk uploads preserve writing and cancellation frees the reservation');
}finally{await browser.close()}})().catch(e=>{console.error(e);process.exitCode=1;});
